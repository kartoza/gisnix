ON = "●"
IMPLIED = "◐"
OFF = "○"
#: Radio marks, for members of a one-of group. Deliberately a different shape
#: from the checkbox marks above: these are alternatives, and picking one
#: unpicks its siblings, which a row that looks identical to a checkbox would
#: not lead anyone to expect.
PICKED = "◉"
UNPICKED = "◯"


@dataclass
class Result:
    """What the chooser hands back: a selection, and any module edits staged."""

    selected: set[str]
    #: module path -> the packages it should end up installing.
    edits: dict[Path, set[str]]
    #: choice key -> the member picked, e.g. {"locale": "pt-en",
    #: "kernel": "latest"}. These are scalar keys in config.nix, not entries
    #: in `bundles`, because their members are alternatives.
    choices: dict[str, str] = field(default_factory=dict)

INDEX_PATH = H.REPO_ROOT / "docs" / "references" / "software.json"


@lru_cache(maxsize=1)
def package_index() -> dict[str, dict]:
    """package name -> nixpkgs metadata, or {} when the index is absent."""
    try:
        return json.loads(INDEX_PATH.read_text())
    except (OSError, ValueError):
        return {}


def _nearest_selectable(options: list[Option], at: int) -> int:
    """The closest index to `at` that is not a disabled row.

    Module headings are disabled, so a restored position can land on one.
    Textual will not highlight a disabled option, and asking it to is how the
    cursor ends up somewhere unrelated.
    """
    if not options[at].disabled:
        return at
    for step in range(1, len(options)):
        for candidate in (at - step, at + step):
            if 0 <= candidate < len(options) and not options[candidate].disabled:
                return candidate
    return at


