"""The three-pane bundle chooser behind `gisnix configure`.

    ┌──────────────────┬────────────────────────────────┐
    │ bundles          │ what this bundle installs      │
    │ ● base           │   • firefox                    │   upper ¾
    │ ○ desktop-gis    │   • brave                      │
    ├──────────────────┴────────────────────────────────┤
    │ detail of whatever is highlighted                 │   lower ¼
    └───────────────────────────────────────────────────┘

Tab moves between the two upper panes, and the bottom pane follows whichever
has focus: the bundle on the left, or the individual package on the right.
Choosing between `desktop-multimedia` and `desktop-productivity` from their
names alone is guesswork — seeing that one of them is what installs `obs` is
not.

WHERE THE PACKAGE DESCRIPTIONS COME FROM

`docs/references/software.json`, written by
`docs/scripts/generate-software-catalogue.py` out of nixpkgs metadata. That
generator runs a `nix eval` over every host and takes minutes; a pane that
redraws on every cursor movement has milliseconds, so it reads the answer
that run already worked out rather than asking again.

The consequence is honest and stated in the pane: a package no host installs
is not in the index, and is shown as "not in the catalogue" rather than as
having no description. The index is regenerated by the docs workflow.

WHY TEXTUAL

`gum choose` is a single column with no cursor-moved event, so there is
nothing to hang a live pane on — a hard limit of the tool. Textual comes from
the flake (`pythonDeps` in `utils/commands.json`), never from pip. If it is
somehow absent, `utils/configure.py` falls back to the gum picker: nothing
here is load-bearing for correctness, since every guarantee about what gets
written lives in `utils/lib/hostconfig.py`, which this only hands a set of
names to.
"""

